export const SHELL_START = [
  'cd -P "$AVEN_THREAD_DIR" || exit 1',
  "export BASH_SILENCE_DEPRECATION_WARNING=1",
  "origin=$(git remote get-url origin 2>/dev/null)",
  "branch=$(git branch --show-current 2>/dev/null)",
  'if [ -n "$origin" ] && [ -n "$branch" ]; then',
  '  AVEN_PROMPT_NAME=$(basename "${origin%.git}")',
  `  printf '\\033[2m%s · %s (isolated copy)\\033[0m\\n' "$AVEN_PROMPT_NAME" "$branch"`,
  "else",
  '  AVEN_PROMPT_NAME=$(basename "$PWD")',
  `  printf '\\033[2m%s\\033[0m\\n' "$PWD"`,
  "fi",
  "export AVEN_PROMPT_NAME",
  `export PROMPT_COMMAND='PS1="\\[\\e[34m\\]$AVEN_PROMPT_NAME\\[\\e[0m\\]$(b=$(git branch --show-current 2>/dev/null); [ -n "$b" ] && printf " \\[\\e[2m\\](%s)\\[\\e[0m\\]" "$b") \\$ "'`,
  "exec bash",
].join("\n");
